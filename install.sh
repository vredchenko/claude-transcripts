#!/bin/sh
# Claude Transcripts installer.
#
#   curl -fsSL https://raw.githubusercontent.com/vredchenko/claude-transcripts/main/install.sh | sh
#
# This wrapper deliberately does almost nothing: detect the platform, fetch the
# matching release binary, verify it, and hand over to `claude-transcripts install`,
# which does the actual work. Anything implemented here couldn't be tested, reused by a
# future `upgrade`, or run by someone who already has the binary — so it lives in the CLI.
# (`upgrade` is not implemented yet; see docs/start/installation.md#upgrading.)
#
#   CT_INSTALL_VERSION=v0.1.0   install a specific release (default: latest)
#                               (CT_VERSION still works for now, deprecated)
#   CT_INSTALL_TARGET=linux-x64-musl   use this release asset instead of detecting one
#   CT_DOWNLOAD_URL=<url>       fetch the assets from here instead of the GitHub release,
#                               e.g. an omnibus instance's /downloads (no version lookup)
#   CT_BIN_DIR=~/.local/bin
#   CT_NO_RUN=1         install the binary only; don't run `install`
#
# POSIX sh, no bashisms: this has to run under dash, ash and busybox.
set -eu

REPO="vredchenko/claude-transcripts"
# The release assets, from the blueprint (packages/shared/src/blueprint/cli-targets.ts).
# gen:cli-targets:start — generated by `bun run gen:distributions`; do not edit
SUPPORTED_TARGETS="linux-x64 linux-x64-baseline linux-x64-musl linux-x64-musl-baseline linux-arm64 linux-arm64-musl darwin-x64 darwin-arm64"
# gen:cli-targets:end
# Prefix for the files detection reads (/proc/cpuinfo, /etc/alpine-release, the
# libstdc++ check). Empty in real use; install.test.ts points it at a fake system.
SYSROOT="${_CT_SYSROOT:-}"
BIN_DIR="${CT_BIN_DIR:-$HOME/.local/bin}"
BIN_NAME="claude-transcripts"

info() { printf '  %s\n' "$*"; }
die() { printf 'install.sh: %s\n' "$*" >&2; exit 1; }

need() {
  command -v "$1" >/dev/null 2>&1 || die "\`$1\` is required but not installed."
}

# ── Platform ────────────────────────────────────────────────────────────────
# musl libc: Alpine says so in a file; elsewhere `ldd --version` names its libc.
is_musl() {
  [ -e "$SYSROOT/etc/alpine-release" ] && return 0
  ldd --version 2>&1 | grep -qi musl
}

# The default x64 builds need AVX2; without it they die with "Illegal instruction".
# Unknown (no readable cpuinfo) counts as "no": the baseline build runs everywhere.
has_avx2() {
  grep -qw avx2 "$SYSROOT/proc/cpuinfo" 2>/dev/null
}

detect_target() {
  os="$(uname -s)"
  arch="$(uname -m)"
  case "$os" in
    Linux) os_part="linux" ;;
    Darwin) os_part="darwin" ;;
    *) die "unsupported OS: $os (Linux and macOS only; on Windows use WSL2)" ;;
  esac
  case "$arch" in
    x86_64 | amd64) arch_part="x64" ;;
    arm64 | aarch64) arch_part="arm64" ;;
    *) die "unsupported architecture: $arch (release binaries: $SUPPORTED_TARGETS)" ;;
  esac
  target="$os_part-$arch_part"
  if [ "$os_part" = "linux" ]; then
    if is_musl; then target="$target-musl"; fi
    if [ "$arch_part" = "x64" ] && ! has_avx2; then target="$target-baseline"; fi
  fi
  printf '%s' "$target"
}

is_supported() {
  case " $SUPPORTED_TARGETS " in
    *" $1 "*) return 0 ;;
    *) return 1 ;;
  esac
}

# The musl builds link the C++ runtime dynamically, and a minimal Alpine doesn't have
# it. Say so before downloading 100 MB, not as a cryptic loader error after.
check_musl_runtime() {
  case "$1" in *-musl*) ;; *) return 0 ;; esac
  for lib in libstdc++.so.6 libgcc_s.so.1; do
    found=""
    for d in /usr/lib /lib /usr/local/lib; do
      [ -e "$SYSROOT$d/$lib" ] && found=1
    done
    [ -n "$found" ] || die "$1 needs libstdc++ and libgcc, and $lib is missing. On Alpine: apk add libstdc++ libgcc"
  done
}

# ── Release resolution ──────────────────────────────────────────────────────
latest_version() {
  # Read the tag from the redirect to /releases/latest — no jq, no API token.
  curl -fsSLI -o /dev/null -w '%{url_effective}' \
    "https://github.com/$REPO/releases/latest" | sed 's#.*/tag/##'
}

main() {
  need curl
  need uname

  if [ -n "${CT_INSTALL_TARGET:-}" ]; then
    target="$CT_INSTALL_TARGET"
  else
    target="$(detect_target)"
  fi
  is_supported "$target" \
    || die "no release binary for $target. Available: $SUPPORTED_TARGETS (set CT_INSTALL_TARGET to choose one)"
  check_musl_runtime "$target"
  if [ -z "${CT_INSTALL_VERSION:-}" ] && [ -n "${CT_VERSION:-}" ]; then
    info "CT_VERSION is deprecated here; use CT_INSTALL_VERSION"
    CT_INSTALL_VERSION="$CT_VERSION"
  fi
  asset="$BIN_NAME-$target"
  if [ -n "${CT_DOWNLOAD_URL:-}" ]; then
    base="${CT_DOWNLOAD_URL%/}"
    printf 'Claude Transcripts from %s (%s)\n' "$base" "$target"
  else
    version="${CT_INSTALL_VERSION:-$(latest_version)}"
    [ -n "$version" ] || die "could not resolve the latest release version."
    base="https://github.com/$REPO/releases/download/$version"
    printf 'Claude Transcripts %s (%s)\n' "$version" "$target"
  fi

  tmp="$(mktemp -d)"
  # Clean up on any exit, including the failures below.
  trap 'rm -rf "$tmp"' EXIT INT TERM

  info "downloading $asset"
  curl -fsSL "$base/$asset" -o "$tmp/$BIN_NAME" \
    || die "download failed: $base/$asset"

  # Verify against the release checksum. Piping a binary from the internet into your
  # shell's PATH without checking it is not something to be relaxed about — so a
  # missing or unreadable checksum is a failure, not a shrug.
  #
  # The file is `<asset>.sha256`, published per-asset by release-cli.yml. This used to
  # look for a combined `checksums.txt`, which no release has ever contained: the fetch
  # 404'd, the "no checksums published" branch ran, and every install silently skipped
  # verification while reporting success.
  curl -fsSL "$base/$asset.sha256" -o "$tmp/$asset.sha256" \
    || die "no checksum published for $asset at $base — refusing to install."

  # `sha256sum -c` needs the file beside the sum, and the sum names the original asset.
  expected="$(awk '{print $1}' "$tmp/$asset.sha256")"
  [ -n "$expected" ] || die "checksum file for $asset is empty — refusing to install."

  if command -v sha256sum >/dev/null 2>&1; then
    actual="$(sha256sum "$tmp/$BIN_NAME" | awk '{print $1}')"
  elif command -v shasum >/dev/null 2>&1; then
    actual="$(shasum -a 256 "$tmp/$BIN_NAME" | awk '{print $1}')"
  else
    die "no sha256sum or shasum available to verify the download — refusing to install."
  fi

  [ "$actual" = "$expected" ] || die "checksum mismatch for $asset — refusing to install."
  info "checksum verified"

  # Run it before putting it on PATH: a binary this machine can't execute (wrong libc,
  # a CPU without AVX2 that detection missed) should fail here, with a way forward.
  chmod +x "$tmp/$BIN_NAME"
  if ! "$tmp/$BIN_NAME" --version >/dev/null 2>"$tmp/run.err"; then
    sed 's/^/    /' "$tmp/run.err" | head -5 >&2
    case "$target" in
      linux-x64 | linux-x64-musl)
        die "$asset doesn't run here. If the error is \"Illegal instruction\", the CPU lacks AVX2: re-run with CT_INSTALL_TARGET=$target-baseline" ;;
      *) die "$asset doesn't run on this machine (see above)." ;;
    esac
  fi

  mkdir -p "$BIN_DIR"
  mv "$tmp/$BIN_NAME" "$BIN_DIR/$BIN_NAME"
  info "installed $BIN_DIR/$BIN_NAME"

  case ":$PATH:" in
    *":$BIN_DIR:"*) ;;
    *) info "note: $BIN_DIR is not on your PATH — add: export PATH=\"$BIN_DIR:\$PATH\"" ;;
  esac

  [ "${CT_NO_RUN:-}" = "1" ] && { info "CT_NO_RUN=1 — skipping setup"; exit 0; }

  printf '\n'
  # Hand over. Everything real happens here.
  exec "$BIN_DIR/$BIN_NAME" install "$@"
}

# install.test.ts sources this file for its functions without running the installer.
[ "${_CT_SOURCE_ONLY:-}" = "1" ] || main "$@"
