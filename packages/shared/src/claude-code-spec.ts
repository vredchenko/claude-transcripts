/**
 * Claude Code's hook surface as data, and the check that compares it with ours
 * ([ADR 0025](../../../docs/design/decisions/0025-claude-code-compatibility-matrix.md)).
 *
 * The source of truth is `@anthropic-ai/claude-agent-sdk` on npm. Every Claude Code
 * release ships a matching SDK release whose `package.json` names it
 * (`claudeCodeVersion`), and whose `sdk.d.ts` declares `HOOK_EVENTS` and one
 * `<Event>HookInput` type per event. A published npm version never changes, so "the
 * hook spec of Claude Code X" is one exact, reproducible answer — not a scrape of
 * prose docs that can move under us.
 *
 * Pure TS on purpose: the generator (`scripts/regenerate-compatibility.ts`), the CLI's
 * on-demand fetch and the hook's session-start check all share this, and none of it
 * touches the network or the filesystem.
 */
import type { HookTypeDef } from "./blueprint/types";
import verified from "./claude-code-hook-spec.json";

/**
 * One event's payload fields. The value lists a field's allowed values when its type
 * is a closed set of string literals (`source`, `reason`, …), and is empty otherwise.
 */
export type HookFields = Record<string, string[]>;

export interface HookSpec {
  /** The Claude Code version this spec describes. */
  claudeCode: string;
  /** The `@anthropic-ai/claude-agent-sdk` version it was read from. */
  sdk: string;
  /** Fields every event carries (`BaseHookInput`). */
  base: HookFields;
  /** Every event Claude Code fires, in `HOOK_EVENTS` order, with its own fields. */
  events: Record<string, HookFields>;
}

/**
 * The spec this build was checked against — generated by `bun run gen:compat`, which
 * pins the Claude Code version it names. `bun run gen:compat --latest` moves the pin.
 */
export const VERIFIED_HOOK_SPEC: HookSpec = verified;

// ── Reading sdk.d.ts ───────────────────────────────────────────────────────────

/** `/** … *\/` and `// …` comments, which carry prose that would confuse the walk below. */
function stripComments(src: string): string {
  return src.replace(/\/\*[\s\S]*?\*\//g, "").replace(/^\s*\/\/.*$/gm, "");
}

/** The text of `export declare type <name> = …;`, up to its closing `;`, or null. */
function typeBody(dts: string, name: string): string | null {
  const head = `export declare type ${name} = `;
  const start = dts.indexOf(head);
  if (start < 0) return null;
  let depth = 0;
  for (let i = start + head.length; i < dts.length; i++) {
    const c = dts[i];
    if (c === "{" || c === "(") depth++;
    else if (c === "}" || c === ")") depth--;
    else if (c === ";" && depth === 0) return stripComments(dts.slice(start + head.length, i));
  }
  return null;
}

/** One string literal; releases have used both quote styles. */
const LIT = `(?:'[^']*'|"[^"]*")`;
/** A closed set of string literals: `'a' | 'b'`. */
const LIT_UNION = new RegExp(`^${LIT}(?:\\s*\\|\\s*${LIT})*$`);

/** Top-level string-literal unions (`type ExitReason = 'clear' | 'other';`), by name. */
function literalAliases(dts: string): Map<string, string[]> {
  const out = new Map<string, string[]>();
  const re = /^export declare type (\w+) = (.+);$/gm;
  for (const m of dts.matchAll(re)) {
    if (LIT_UNION.test(m[2]!)) out.set(m[1]!, literals(m[2]!));
  }
  return out;
}

function literals(src: string): string[] {
  return [...src.matchAll(/'([^']*)'|"([^"]*)"/g)].map((m) => (m[1] ?? m[2])!).sort();
}

/**
 * The properties declared directly inside the object literals of a type body —
 * nested objects (`effort?: { level }`) are one field, not two. `hook_event_name` is
 * the discriminator, not data, so it is left out.
 */
function fieldsOf(body: string, aliases: Map<string, string[]>): HookFields {
  const fields: HookFields = {};
  let depth = 0;
  for (const line of body.split("\n")) {
    if (depth === 1) {
      const m = /^\s*(\w+)\??:\s*(.*)$/.exec(line);
      if (m && m[1] !== "hook_event_name") {
        const type = m[2]!.replace(/;\s*$/, "").trim();
        if (LIT_UNION.test(type)) fields[m[1]!] = literals(type);
        else fields[m[1]!] = aliases.get(type) ?? [];
      }
    }
    for (const c of line) {
      if (c === "{") depth++;
      else if (c === "}") depth--;
    }
  }
  return Object.fromEntries(Object.entries(fields).sort(([a], [b]) => a.localeCompare(b)));
}

/**
 * Read the hook spec out of an SDK release's `sdk.d.ts`. Throws when `HOOK_EVENTS` or
 * `BaseHookInput` is missing: a spec that silently came out empty would report every
 * event as gone, which is the one failure worse than no check at all.
 */
export function parseSdkHookSpec(
  source: string,
  versions: { claudeCode: string; sdk: string },
): HookSpec {
  // The published file has CRLF line endings, which `$` in a multiline regex won't take.
  const dts = source.replace(/\r\n/g, "\n");
  const list = /export declare const HOOK_EVENTS: readonly \[([^\]]*)\]/.exec(dts);
  if (!list) throw new Error("sdk.d.ts declares no HOOK_EVENTS — the SDK's layout changed");
  const baseBody = typeBody(dts, "BaseHookInput");
  if (!baseBody) throw new Error("sdk.d.ts declares no BaseHookInput — the SDK's layout changed");
  const aliases = literalAliases(dts);
  const events: Record<string, HookFields> = {};
  // In declaration order, not `literals`' sorted order: the spec keeps HOOK_EVENTS order.
  const names = [...list[1]!.matchAll(/'([^']+)'|"([^"]+)"/g)].map((m) => (m[1] ?? m[2])!);
  if (!names.length) throw new Error("sdk.d.ts lists no HOOK_EVENTS — the SDK's layout changed");
  for (const event of names) {
    const body = typeBody(dts, `${event}HookInput`);
    events[event] = body ? fieldsOf(body, aliases) : {};
  }
  return { ...versions, base: fieldsOf(baseBody, aliases), events };
}

// ── Comparing ──────────────────────────────────────────────────────────────────

/** Field-level change on one recorded event (or the common fields, as `*`). */
export interface FieldDrift {
  event: string;
  /** `name`, or `name=value` for a value added to a closed set. */
  added: string[];
  removed: string[];
}

export interface HookCompatReport {
  /** The Claude Code version running this session. */
  running: string;
  /** The Claude Code version this build's spec was generated from. */
  verified: string;
  /** False when no spec for `running` is to hand — every list below is then empty. */
  known: boolean;
  /** Events Claude Code fires that our catalogue doesn't list at all. */
  unlisted: string[];
  /** Events we register a handler for that this Claude Code doesn't fire. */
  goneWired: string[];
  /** Events we list (unwired) that this Claude Code doesn't fire. */
  goneListed: string[];
  /** Fields that changed between `verified` and `running`, on events we record. */
  fields: FieldDrift[];
  eventCount: number;
  wiredCount: number;
}

function flatten(fields: HookFields): Set<string> {
  const out = new Set<string>();
  for (const [name, values] of Object.entries(fields)) {
    out.add(name);
    for (const v of values) out.add(`${name}=${v}`);
  }
  return out;
}

/**
 * `name=value` entries are dropped when `name` itself was added or removed — "the
 * field went away" already says its values did.
 */
function fieldDrift(event: string, before: HookFields, after: HookFields): FieldDrift | null {
  const a = flatten(before);
  const b = flatten(after);
  const whole = (s: string, other: Set<string>) => !other.has(s.split("=")[0]!);
  const added = [...b].filter((f) => !a.has(f) && (!f.includes("=") || !whole(f, a))).sort();
  const removed = [...a].filter((f) => !b.has(f) && (!f.includes("=") || !whole(f, b))).sort();
  return added.length || removed.length ? { event, added, removed } : null;
}

/**
 * Compare the running Claude Code's spec with our catalogue (which events exist) and
 * with the spec this build was verified against (what changed in the payloads we
 * record). `running` is null when no spec for that version is to hand yet.
 */
export function compareHookSpec(
  catalogue: HookTypeDef[],
  verified: HookSpec,
  runningVersion: string,
  running: HookSpec | null,
): HookCompatReport {
  const wired = catalogue.filter((h) => h.wired);
  const report: HookCompatReport = {
    running: runningVersion,
    verified: verified.claudeCode,
    known: running !== null,
    unlisted: [],
    goneWired: [],
    goneListed: [],
    fields: [],
    eventCount: running ? Object.keys(running.events).length : 0,
    wiredCount: wired.length,
  };
  if (!running) return report;

  const listed = new Set(catalogue.map((h) => h.event));
  report.unlisted = Object.keys(running.events)
    .filter((e) => !listed.has(e))
    .sort();
  for (const h of catalogue) {
    if (h.event in running.events) continue;
    (h.wired ? report.goneWired : report.goneListed).push(h.event);
  }
  const base = fieldDrift("*", verified.base, running.base);
  if (base) report.fields.push(base);
  for (const h of wired) {
    const after = running.events[h.event];
    if (!after) continue;
    const drift = fieldDrift(h.event, verified.events[h.event] ?? {}, after);
    if (drift) report.fields.push(drift);
  }
  return report;
}

export function hasDrift(r: HookCompatReport): boolean {
  return (
    !r.known ||
    r.unlisted.length > 0 ||
    r.goneWired.length > 0 ||
    r.goneListed.length > 0 ||
    r.fields.length > 0
  );
}

/**
 * The report as plain-text lines for the session-start banner (no colour, no links —
 * a banner can't draw either). One line when all is well; a short summary otherwise,
 * ending with where to look for the rest.
 */
export function formatHookCompat(r: HookCompatReport): string[] {
  if (!r.known) {
    return [
      `? Hook spec for Claude Code ${r.running} not checked yet (this build knows ${r.verified}) — fetching it; the result shows next session`,
    ];
  }
  if (!hasDrift(r)) {
    return [
      `✓ Hook spec matches Claude Code ${r.running} (${r.eventCount} events, ${r.wiredCount} recorded)`,
    ];
  }
  const against = r.running === r.verified ? "" : ` (this build was checked against ${r.verified})`;
  const lines = [`△ Hook spec drift with Claude Code ${r.running}${against}:`];
  const list = (xs: string[]) => xs.join(", ");
  if (r.goneWired.length) lines.push(`  · recorded, but no longer fired: ${list(r.goneWired)}`);
  if (r.unlisted.length) lines.push(`  · new events we don't handle: ${list(r.unlisted)}`);
  if (r.goneListed.length) lines.push(`  · listed, but no longer fired: ${list(r.goneListed)}`);
  for (const f of r.fields) {
    const name = f.event === "*" ? "common fields" : f.event;
    const parts = [...f.added.map((x) => `+${x}`), ...f.removed.map((x) => `−${x}`)];
    lines.push(`  · ${name}: ${parts.join(" ")}`);
  }
  lines.push("  Details: claude-transcripts compat");
  return lines;
}
