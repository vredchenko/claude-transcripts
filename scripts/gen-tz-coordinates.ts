/**
 * Regenerate `packages/webui/src/tz-coordinates.ts` — each IANA time zone's reference
 * point, from the tz database's own `zone.tab` and `zone1970.tab`, plus
 * the legacy names `tzdata.zi` links to them.
 *
 * The calendar shades each day by daylight, which needs a latitude and longitude. With
 * no `userSettings.location` configured, the browser's time zone is the best zero-config
 * guess there is, and the tz database already records where each zone is (its principal
 * city). Coordinates are rounded to 0.01° — far finer than shading needs.
 *
 * Not part of `gen:all`: the output depends on the tzdata installed where it runs, and
 * zone coordinates change about never. Re-run by hand after a tzdata release that adds
 * zones:
 *
 *   bun run gen:tz [path/to/zoneinfo]   # default /usr/share/zoneinfo
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const zoneinfo = process.argv[2] ?? "/usr/share/zoneinfo";
const OUT = join(import.meta.dir, "..", "packages", "webui", "src", "tz-coordinates.ts");

/** `+DDMM`, `+DDMMSS`, `+DDDMM`, `+DDDMMSS` → signed decimal degrees. */
function degrees(part: string, degDigits: number): number {
  const sign = part.startsWith("-") ? -1 : 1;
  const digits = part.slice(1);
  const d = Number(digits.slice(0, degDigits));
  const m = Number(digits.slice(degDigits, degDigits + 2));
  const s = Number(digits.slice(degDigits + 2) || "0");
  return sign * (d + m / 60 + s / 3600);
}

const zones = new Map<string, [number, number]>();
for (const file of ["zone1970.tab", "zone.tab"]) {
  const path = join(zoneinfo, file);
  if (!existsSync(path)) continue;
  for (const line of readFileSync(path, "utf8").split("\n")) {
    if (!line || line.startsWith("#")) continue;
    const [, coords, zone] = line.split("\t");
    if (!coords || !zone || zones.has(zone)) continue;
    const match = /^([+-]\d+)([+-]\d+)$/.exec(coords);
    if (!match?.[1] || !match[2]) continue;
    const lat = degrees(match[1], 2);
    const lon = degrees(match[2], 3);
    zones.set(zone, [Math.round(lat * 100) / 100, Math.round(lon * 100) / 100]);
  }
}
if (zones.size === 0) throw new Error(`no zone.tab / zone1970.tab under ${zoneinfo}`);

// Legacy names are links to a current zone (`L <target> <alias>` in tzdata.zi), and
// browsers still report some of them — Chrome says Asia/Calcutta and Europe/Kiev.
const zi = join(zoneinfo, "tzdata.zi");
if (existsSync(zi)) {
  for (const line of readFileSync(zi, "utf8").split("\n")) {
    const [kind, target, alias] = line.split(" ");
    if (kind !== "L" || !target || !alias || zones.has(alias)) continue;
    const at = zones.get(target);
    if (at) zones.set(alias, at);
  }
}

const rows = [...zones.entries()]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([zone, [lat, lon]]) => `  "${zone}": [${lat}, ${lon}],`)
  .join("\n");

writeFileSync(
  OUT,
  `// Generated by scripts/gen-tz-coordinates.ts from the tz database's zone.tab and
// zone1970.tab, plus the legacy names tzdata.zi links to them — do not edit. Each IANA
// zone's reference point, [latitude, longitude] in decimal degrees (north and east positive).

export const TZ_COORDINATES: Record<string, readonly [number, number]> = {
${rows}
};
`,
);
console.log(`wrote ${zones.size} zones → ${OUT}`);
